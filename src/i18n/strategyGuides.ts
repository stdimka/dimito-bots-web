const BY_LOCALE: Record<Locale, Record<string, StrategyGuide>> = {
  ru: GUIDES_RU,
  en: GUIDES_EN,
};

const CATEGORY_LABELS: Record<Locale, Record<string, string>> = {
  ru: {
    trend: "Тренд",
    reversion: "Отскок",
    breakout: "Пробой",
    liquidity: "Уровни",
    pattern: "Свечи",
  },
  en: {
    trend: "Trend",
    reversion: "Bounce",
    breakout: "Breakout",
    liquidity: "Levels",
    pattern: "Candles",
  },
};

export function getStrategyGuide(
  strategy: string,
  locale: Locale,
): StrategyGuide | null {
  const key = strategyGuideKey(strategy);
  const pack = BY_LOCALE[locale] ?? GUIDES_RU;
  return pack[key] ?? GUIDES_RU[key] ?? GUIDES_EN[key] ?? null;
}

export function getCategoryLabel(category: string, locale: Locale): string {
  return CATEGORY_LABELS[locale]?.[category] ?? category;
}

export function listGuideKeys(): string[] {
  return Object.keys(GUIDES_RU);
}
